function formatDay(day) {
  return String(day).padStart(2, '0');
}

function buildDetailRows() {
  const assignees = [
    'Иван Петров',
    'Анна Смирнова',
    'Дмитрий Кузнецов',
    'Ольга Иванова',
    'Сергей Волков',
    'Мария Федорова',
    'Павел Егоров',
    'Наталья Орлова',
    'Алексей Морозов',
    'Елена Жукова',
    'Роман Белов',
    'Виктория Никитина',
    'Кирилл Соколов',
    'Ирина Лебедева'
  ];

  return MASTER_ROWS.flatMap((team, teamIndex) => {
    return DETAIL_TEMPLATES.map((template, templateIndex) => {
      const dayStart = (teamIndex * 2 + templateIndex) % 18 + 1;
      const dayEnd = dayStart + 3;
      const taskNo = 100 + teamIndex * 10 + templateIndex + 1;
      return {
        team_id: team.team_id,
        task_key: `${team.team_id.toUpperCase()}-${taskNo}`,
        title: `${template.title} (${team.direction})`,
        type: template.type,
        status: template.status,
        priority: template.priority,
        assignee: assignees[(teamIndex + templateIndex) % assignees.length],
        start_date: `2026-02-${formatDay(dayStart)}`,
        due_date: `2026-02-${formatDay(dayEnd)}`,
        customer_impact: template.customer_impact,
        blocked_by: template.blocked_by,
        notes: template.notes,
        estimate_h: template.estimate_h + (teamIndex % 3),
        spent_h: template.spent_h + (templateIndex % 2),
        remain_h: template.remain_h + (teamIndex % 2),
        qa_status: template.qa_status,
        test_coverage_pct: template.test_coverage_pct + (teamIndex % 6),
        build_tag: `${template.build_tag}-${teamIndex + 1}`,
        environment: template.environment,
        release_window: template.release_window,
        risk_level: template.risk_level
      };
    });
  });
}

const DETAIL_ROWS = buildDetailRows();

