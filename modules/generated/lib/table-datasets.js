function buildDeepGroupRows() {
  const teams = [
    { service: 'API Gateway', owner: 'Иван Петров', k: 1.0 },
    { service: 'Web Frontend', owner: 'Анна Смирнова', k: 0.9 },
    { service: 'Payments', owner: 'Дмитрий Кузнецов', k: 1.2 },
    { service: 'Search Service', owner: 'Ольга Иванова', k: 0.85 },
    { service: 'Auth Service', owner: 'Кирилл Соколов', k: 1.05 },
    { service: 'Mobile API', owner: 'Алексей Морозов', k: 0.95 },
    { service: 'Data Platform', owner: 'Наталья Орлова', k: 1.1 },
    { service: 'Observability', owner: 'Елена Жукова', k: 0.8 }
  ];

  return teams.map((team, index) => {
    const base = 80 + index * 7;
    const planShift = Math.round(base * team.k);
    const factShift = Math.round(planShift * (0.92 + (index % 3) * 0.04));
    const incOpen = Math.max(0, 8 - index);
    const incClosed = incOpen + 6 + (index % 4);
    const slaHit = Math.max(92, 99 - (index % 5));

    return {
      service: team.service,
      owner: team.owner,
      jan_plan: planShift,
      jan_fact: factShift,
      feb_plan: planShift + 4,
      feb_fact: factShift + 5,
      apr_plan: planShift + 8,
      apr_fact: factShift + 9,
      may_plan: planShift + 6,
      may_fact: factShift + 7,
      inc_open: incOpen,
      inc_closed: incClosed,
      sla_hit_pct: slaHit,
      status: incOpen <= 2 ? 'Стабильно' : (incOpen <= 5 ? 'Контроль' : 'Риск')
    };
  });
}

